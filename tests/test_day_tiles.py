VIEWS = {"money": ["overview", "bills", "budget", "pay", "goals"], "tasks": ["todo", "lists", "routines", "leave"]}
def cards_on(a, tab):                                                       # every section of the tab
    a.js("DT_SCREEN = null")
    out = set()
    for v in VIEWS.get(tab, [None]):
        if v: a.js(f"{'DT_MONEY' if tab == 'money' else 'DT_TASKS'} = '{v}'")
        a.js(f"shellGo('{tab}')")
        out |= set(a.js("[...document.querySelectorAll('#cards [data-card]')].map(e => e.dataset.card)"))
    return sorted(out)


