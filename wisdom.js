const WD = (() => {                                       // famous lines spread evenly through the year
  const out = [];
  let a = 0, b = 0;
  while (a < WD_A.length || b < WD_B.length) {
    if (b >= WD_B.length || (a < WD_A.length && a / WD_A.length <= b / WD_B.length)) out.push(WD_A[a++]);
    else out.push([WD_B[b++], ""]);
  }
  return out;
})();
// The day's saying: day of the year, so every phone shows the same one on the same date.
function wdFor(day) {
  const [y, m, d] = String(day || today()).split("-").map(Number);
  const n = Math.round((Date.UTC(y, m - 1, d) - Date.UTC(y, 0, 1)) / 864e5);
  return WD[((n % WD.length) + WD.length) % WD.length];
}
